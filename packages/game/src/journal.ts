import { ChessState, toPgn } from "@chessonglass/chess";
import type {
  GamePosition,
  PositionUncertainty,
  SessionId
} from "@chessonglass/contracts";

export type GameRecord = {
  schemaVersion: 1;
  sessionId: SessionId;
  position: GamePosition;
  positionVersion: number;
  createdAtWallMs: number;
  updatedAtWallMs: number;
};

/**
 * A record loaded from disk. The physical board may have changed while the app
 * was closed, so resuming always requires the user to confirm the position.
 */
export type ResumableGameRecord = GameRecord & {
  readonly resumeRequiresConfirmation: true;
};

export class InvalidGameRecordError extends Error {
  constructor(detail: string) {
    super(`invalid game record: ${detail}`);
    this.name = "InvalidGameRecordError";
  }
}

const SESSION_ID_PATTERN =
  /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

const RECORD_KEYS = [
  "schemaVersion",
  "sessionId",
  "position",
  "positionVersion",
  "createdAtWallMs",
  "updatedAtWallMs"
] as const;

const POSITION_KEYS = ["initialFen", "fen", "history", "uncertainty"] as const;

const UNCERTAINTY_KEYS = [
  "castlingRights",
  "enPassant",
  "promotion"
] as const;

type UnknownRecord = Record<string, unknown>;

/** Canonical IDs are generated by `newSessionId` and used only as hash input. */
export function isCanonicalSessionId(value: unknown): value is SessionId {
  return typeof value === "string" && SESSION_ID_PATTERN.test(value);
}

function isPlainObject(value: unknown): value is UnknownRecord {
  if (typeof value !== "object" || value === null || Array.isArray(value)) {
    return false;
  }
  const prototype = Object.getPrototypeOf(value);
  return prototype === Object.prototype || prototype === null;
}

function hasExactKeys(
  value: UnknownRecord,
  expected: readonly string[]
): boolean {
  const keys = Object.keys(value);
  return (
    keys.length === expected.length &&
    expected.every((key) => Object.hasOwn(value, key))
  );
}

function requireObject(value: unknown, label: string): UnknownRecord {
  if (!isPlainObject(value)) {
    throw new InvalidGameRecordError(`${label} must be an object`);
  }
  return value;
}

function requireString(value: unknown, label: string): string {
  if (typeof value !== "string" || value.length === 0) {
    throw new InvalidGameRecordError(`${label} must be a non-empty string`);
  }
  return value;
}

function requireBoolean(value: unknown, label: string): boolean {
  if (typeof value !== "boolean") {
    throw new InvalidGameRecordError(`${label} must be a boolean`);
  }
  return value;
}

function requireSafeInteger(
  value: unknown,
  label: string,
  minimum: number
): number {
  if (
    typeof value !== "number" ||
    !Number.isSafeInteger(value) ||
    value < minimum
  ) {
    throw new InvalidGameRecordError(
      `${label} must be a safe integer >= ${minimum}`
    );
  }
  return value;
}

function readUncertainty(
  value: unknown,
  strictKeys: boolean
): PositionUncertainty {
  const input = requireObject(value, "position.uncertainty");
  if (strictKeys && !hasExactKeys(input, UNCERTAINTY_KEYS)) {
    throw new InvalidGameRecordError(
      "position.uncertainty contains unknown or missing fields"
    );
  }
  return {
    castlingRights: requireBoolean(
      input.castlingRights,
      "position.uncertainty.castlingRights"
    ),
    enPassant: requireBoolean(
      input.enPassant,
      "position.uncertainty.enPassant"
    ),
    promotion: requireBoolean(input.promotion, "position.uncertainty.promotion")
  };
}

/**
 * Replay `initialFen` plus the ordered UCI history and require the stored
 * current FEN to agree. A record whose FEN and history disagree is never
 * treated as valid state.
 */
function readPosition(value: unknown, strictKeys: boolean): GamePosition {
  const input = requireObject(value, "position");
  if (strictKeys && !hasExactKeys(input, POSITION_KEYS)) {
    throw new InvalidGameRecordError(
      "position contains unknown or missing fields"
    );
  }

  const initialFen = requireString(input.initialFen, "position.initialFen");
  const fen = requireString(input.fen, "position.fen");
  if (!Array.isArray(input.history)) {
    throw new InvalidGameRecordError("position.history must be an array");
  }
  const history = input.history.map((move, index) =>
    requireString(move, `position.history[${index}]`)
  );
  const uncertainty = readUncertainty(input.uncertainty, strictKeys);

  let replayed: GamePosition;
  try {
    replayed = ChessState.fromConfirmed({
      fen: initialFen,
      history,
      uncertainty
    }).position();
  } catch (error) {
    throw new InvalidGameRecordError(
      error instanceof Error ? error.message : "position is not playable"
    );
  }

  if (replayed.fen !== fen) {
    throw new InvalidGameRecordError(
      "stored FEN does not match the ordered move history"
    );
  }

  return {
    initialFen,
    fen: replayed.fen,
    history: [...history],
    uncertainty: { ...uncertainty }
  };
}

function readRecord(value: unknown, strictKeys: boolean): GameRecord {
  const input = requireObject(value, "record");
  if (strictKeys && !hasExactKeys(input, RECORD_KEYS)) {
    throw new InvalidGameRecordError(
      "record contains unknown or missing fields"
    );
  }
  if (input.schemaVersion !== 1) {
    throw new InvalidGameRecordError("schemaVersion must be 1");
  }
  if (!isCanonicalSessionId(input.sessionId)) {
    throw new InvalidGameRecordError("sessionId is not a canonical UUID");
  }

  const position = readPosition(input.position, strictKeys);
  const positionVersion = requireSafeInteger(
    input.positionVersion,
    "positionVersion",
    0
  );
  const createdAtWallMs = requireSafeInteger(
    input.createdAtWallMs,
    "createdAtWallMs",
    0
  );
  const updatedAtWallMs = requireSafeInteger(
    input.updatedAtWallMs,
    "updatedAtWallMs",
    0
  );
  if (updatedAtWallMs < createdAtWallMs) {
    throw new InvalidGameRecordError(
      "updatedAtWallMs must not precede createdAtWallMs"
    );
  }

  return {
    schemaVersion: 1,
    sessionId: input.sessionId,
    position,
    positionVersion,
    createdAtWallMs,
    updatedAtWallMs
  };
}

/**
 * Serialize exactly the schema fields. Unknown runtime properties such as
 * frames, image bytes, secrets or pairing values are deliberately dropped.
 */
export function serializeGameRecord(record: GameRecord): string {
  return JSON.stringify(readRecord(record, false));
}

/**
 * Parse already-decoded JSON from an untrusted file. Any malformed, future or
 * extra-field record returns null instead of a partially trusted object.
 */
export function parseGameRecord(value: unknown): GameRecord | null {
  try {
    return readRecord(value, true);
  } catch {
    return null;
  }
}

/** Export PGN from the same stored record used for the loaded position. */
export function recordPgn(record: GameRecord): string {
  const valid = readRecord(record, false);
  return toPgn(
    ChessState.fromConfirmed({
      fen: valid.position.initialFen,
      history: valid.position.history,
      uncertainty: valid.position.uncertainty
    })
  );
}

/** Mark a loaded record so callers cannot resume without confirmation. */
export function markForResume(record: GameRecord): ResumableGameRecord {
  return { ...record, resumeRequiresConfirmation: true };
}
